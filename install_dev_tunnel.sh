#!/usr/bin/env bash
set -euo pipefail

if [[ "${1:-}" == --help || "${1:-}" == -h ]]; then
  printf 'Usage: bash install_dev_tunnel.sh\nInstall Microsoft Dev Tunnels for Linux (x86_64 or ARM64) in ~/.local/bin.\n'
  printf 'Automatically reuse conda ICU libraries when needed; optionally set ICU_LIB_DIR.\n'
  exit 0
fi

if [[ $# -ne 0 ]]; then
  printf 'Unknown argument. Use --help.\n' >&2
  exit 1
fi
if [[ "$(uname -s)" != Linux ]]; then
  printf 'This installer supports Linux only (including WSL).\n' >&2
  exit 1
fi
case "$(uname -m)" in
  x86_64) arch=linux-x64 ;;
  aarch64|arm64) arch=linux-arm64 ;;
  *) printf 'Unsupported CPU architecture: %s\n' "$(uname -m)" >&2; exit 1 ;;
esac
command -v curl >/dev/null || { printf 'curl is required.\n' >&2; exit 1; }

install_dir="$HOME/.local/bin"
mkdir -p "$install_dir"
stage_dir="$(mktemp -d "$install_dir/.devtunnel-download.XXXXXXXX")"
trap 'rm -rf -- "$stage_dir"' EXIT
tmp="$stage_dir/devtunnel.bin"
probe_log="$stage_dir/version.log"
curl --fail --location --show-error --retry 3 --connect-timeout 15 --max-time 180 \
  "https://aka.ms/TunnelsCliDownload/$arch" -o "$tmp"
chmod 755 "$tmp"

probe_version() (
  # A missing ICU aborts .NET. Do not leave core dumps while probing candidates.
  ulimit -c 0
  LD_LIBRARY_PATH="$1" "$tmp" --version
)

icu_candidates() {
  local root path conda_command
  local -a roots=() library_paths=()
  [[ -z "${ICU_LIB_DIR:-}" ]] || printf '%s\0' "$ICU_LIB_DIR"
  IFS=: read -r -a library_paths <<< "${LD_LIBRARY_PATH:-}"
  for path in "${library_paths[@]}"; do
    [[ -z "$path" ]] || printf '%s\0' "$path"
  done
  [[ -z "${CONDA_PREFIX:-}" ]] || roots+=("$CONDA_PREFIX")
  conda_command="$(command -v conda || true)"
  if [[ -z "$conda_command" && -x "${CONDA_EXE:-}" ]]; then
    conda_command="$CONDA_EXE"
  fi
  if [[ -n "$conda_command" ]]; then
    root="$("$conda_command" info --base 2>/dev/null)" && roots+=("$root")
    # Keep the entire absolute path, including spaces in environment names.
    while IFS= read -r path; do
      roots+=("$path")
    done < <("$conda_command" info --envs 2>/dev/null | sed -n 's/^[^/]*\(\/.*\)/\1/p')
    if [[ -f "$conda_command" ]]; then
      roots+=("$(dirname "$(dirname "$conda_command")")")
    fi
  fi
  if [[ -r "$HOME/.conda/environments.txt" ]]; then
    while IFS= read -r path || [[ -n "$path" ]]; do
      [[ -z "$path" ]] || roots+=("$path")
    done < "$HOME/.conda/environments.txt"
  fi
  # Conda need not be activated or on PATH. Limit discovery to installation roots.
  roots+=("$HOME"/*conda* "$HOME"/*forge* "$HOME/.conda"
          /opt/*conda* /opt/*/*conda* /opt/*forge* /usr/local/*conda*
          /home/*/*conda*)
  for root in "${roots[@]}"; do
    [[ -d "$root" ]] || continue
    for path in "$root/lib" "$root"/envs/*/lib; do
      [[ ! -d "$path" ]] || printf '%s\0' "$path"
    done
  done
  printf '%s\0' "$HOME/.local/icu/usr/lib64"
}

has_icu() {
  local pattern file found
  for pattern in libicuuc.so libicui18n.so libicudata.so; do
    found=0
    for file in "$1/$pattern"*; do
      [[ ! -f "$file" ]] || found=1
    done
    [[ "$found" == 1 ]] || return 1
  done
}

icu_dir=''
# Check without a shell-only library path so a successful install also works in
# a fresh terminal. If needed, persist a validated directory in the wrapper.
if ! probe_version '' > "$probe_log" 2>&1; then
  if grep -qi 'ICU' "$probe_log"; then
    printf 'devtunnel needs ICU; looking for existing conda libraries...\n'
    declare -A checked=()
    while IFS= read -r -d '' candidate; do
      [[ -d "$candidate" ]] || continue
      candidate="$(cd "$candidate" && pwd -P)"
      [[ -z "${checked[$candidate]:-}" ]] || continue
      checked["$candidate"]=1
      has_icu "$candidate" || continue
      printf 'Trying ICU: %s\n' "$candidate"
      if probe_version "${candidate}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" > "$stage_dir/candidate.log" 2>&1; then
        icu_dir="$candidate"
        cp "$stage_dir/candidate.log" "$probe_log"
        break
      fi
      cat "$stage_dir/candidate.log" >&2
    done < <(icu_candidates)
  fi
  if [[ -z "$icu_dir" ]]; then
    cat "$probe_log" >&2
    printf 'Downloaded devtunnel could not run; existing installation was not changed.\n' >&2
    if grep -qi 'ICU' "$probe_log"; then
      printf 'No compatible ICU directory was found automatically.\nSet ICU_LIB_DIR=/path/to/conda/env/lib and rerun, or see README section 2.4.\n' >&2
    fi
    exit 1
  fi
fi
cat "$probe_log"

if [[ -n "$icu_dir" ]]; then
  # Quote the discovered path as Bash data, never as executable shell text.
  {
    printf '#!/usr/bin/env bash\n'
    printf '# Generated by install_dev_tunnel.sh; rerun the installer to update.\n'
    printf 'icu_dir=%q\n' "$icu_dir"
    printf 'export LD_LIBRARY_PATH="${icu_dir}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"\n'
    printf 'exec "$(dirname "${BASH_SOURCE[0]}")/devtunnel.bin" "$@"\n'
  } > "$stage_dir/devtunnel"
  chmod 755 "$stage_dir/devtunnel"
  # Verify the actual wrapper before replacing either installed file.
  if ! (ulimit -c 0; "$stage_dir/devtunnel" --version); then
    printf 'ICU wrapper could not run; existing installation was not changed.\n' >&2
    exit 1
  fi
  mv -f "$tmp" "$install_dir/devtunnel.bin"
  mv -f "$stage_dir/devtunnel" "$install_dir/devtunnel"
  printf 'Saved ICU library path: %s\n' "$icu_dir"
else
  mv -f "$tmp" "$install_dir/devtunnel"
fi
printf '\nInstalled: %s/devtunnel\n' "$install_dir"
printf 'Next: copy connection.env, then run bash remote.sh devtunnel login github and bash remote.sh.\n'
printf 'For direct devtunnel commands in this shell: export PATH="$HOME/.local/bin:$PATH"\n'
